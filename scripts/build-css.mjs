import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const currentFile = fileURLToPath(import.meta.url);
const currentDirectory = path.dirname(currentFile);
const projectRoot = path.resolve(currentDirectory, "..");

const sourceDirectory = path.join(projectRoot, "src", "css");
const outputDirectory = path.join(projectRoot, "dist");
const outputFile = path.join(outputDirectory, "styles.css");

/*
 * Files are combined in this exact order.
 *
 * Keep broad foundational styles near the beginning and narrow overrides,
 * responsive styles, and dark-mode rules near the end.
 */
const files = [
  "00.css",
  "10.css",
  "20.css",
  "30.css",
  "40.css",
  "50.css",
  "51.css",
  "52.css",
  "53.css",
  "54.css",
  "55.css",
  "56.css",
  "57.css",
  "60.css",
  "65.css",
  "70.css",
];

async function buildCSS() {
  await mkdir(outputDirectory, { recursive: true });

  const sections = [];

  for (const filename of files) {
    const filePath = path.join(sourceDirectory, filename);

    try {
      const css = await readFile(filePath, "utf8");

      sections.push(
        [
          `/* ============================================================`,
          `   ${filename}`,
          `   ============================================================ */`,
          "",
          css.trim(),
        ].join("\n"),
      );
    } catch (error) {
      if (error.code === "ENOENT") {
        throw new Error(`Missing CSS file: ${filePath}`);
      }

      throw error;
    }
  }

  const output = [
    "/*",
    " * GENERATED FILE",
    " * Do not edit this file directly.",
    " * Edit files in src/css and run npm run build.",
    " */",
    "",
    sections.join("\n\n"),
    "",
  ].join("\n");

  await writeFile(outputFile, output, "utf8");

  console.log(`Built ${path.relative(projectRoot, outputFile)}`);
  console.log(`Combined ${files.length} CSS files.`);
}

buildCSS().catch((error) => {
  console.error(error.message);
  process.exitCode = 1;
});